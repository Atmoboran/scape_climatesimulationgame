# the most simplified climate model
# goals: use in workshop to teach people how modelling works

import numpy as np
import matplotlib.pyplot as plt
import random


# Number of iterations
num_iterations = 25
# configurations
freq_gain_loss = 1  # frequency of times where energy is added to the eq/ lost at the poles
timestep_globalwarming = 15
freq_plot = 1


# Define grid size
grid_size = 3

# Initialize temperature grid with random values
temperature_grid_init = np.zeros((grid_size, grid_size))

value1_eq = random.randint(25, 50)
value2_eq = random.randint(25, 50)
equator_temps = [value1_eq, value2_eq, 135 - value1_eq - value2_eq]
#equator_temps = [value1_eq, value2_eq,random.randint(25, 50)]

#value1_Npol = random.randint(0, 5)
#value2_Npol = random.randint(0, 5)
#pol_temps_N = [value1_Npol, value2_Npol, 20 - value1_Npol - value2_Npol]

#value1_Spol = random.randint(0, 5)
#value2_Spol = random.randint(0, 5)
#pol_temps_S = [value1_Spol, value2_Spol, 20 - value1_Spol - value2_Spol]

pol_temps_N = [0, 0, 0]
pol_temps_S = [0, 0, 0]
temperature_grid_init[1, :] = equator_temps
temperature_grid_init[0, :] = pol_temps_N
temperature_grid_init[2, :] = pol_temps_S

print("Initial Temperature Grid:")
print(temperature_grid_init)

# initalize mean temperature array and temperature array
mean_temp = np.zeros(num_iterations)
mean_temp[0] = np.mean(temperature_grid_init)
temperature_grid = temperature_grid_init
temp_grid_array = np.zeros([num_iterations, grid_size, grid_size])
temp_grid_array[0, :, :] = temperature_grid_init



######
# Simulation loop
for iteration in range(1, num_iterations):

    ### 1. STEP:
        # Move positions
    for i in range(grid_size):
        if i == 1:  # Equator positions move to the left
            temperature_grid[i, :] = np.roll(temperature_grid[i, :], shift=-1)
        else:  # Poles move to the right
            temperature_grid[i, :] = np.roll(temperature_grid[i, :], shift=1)

    ### 2.STEP:
    # Simulation of temp exchange
    for i in range(grid_size):
        for j in range(grid_size):
            if i == 1:  # Equator positions
                equator_temp = temperature_grid[i, j]
                pole_temp_N = temperature_grid[0, j]
                pole_temp_S = temperature_grid[2, j]

                difference_N = equator_temp - pole_temp_N
                difference_S = equator_temp - pole_temp_S

                # check to which pole the temperature difference is larger
                # give this pole a random amount between 0 and half of this difference
                if difference_N > difference_S and pole_temp_N < equator_temp:
                    max_give = difference_N // 2
                    amount_to_give_N = random.randint(0, max_give)  # Random amount to give to North Pole
                    amount_to_give_S = 0
                elif difference_S >= difference_N and pole_temp_S < equator_temp:
                    max_give = difference_S // 2
                    amount_to_give_N = 0
                    amount_to_give_S = random.randint(0, max_give)  # Random amount to give to South Pole
                else:
                    amount_to_give_N = 0
                    amount_to_give_S = 0



                total_given = amount_to_give_N + amount_to_give_S
                temperature_grid[i, j] -= total_given  # Equator gives random points to each pole
                temperature_grid[0, j] += amount_to_give_N  # North Pole receives random points
                temperature_grid[2, j] += amount_to_give_S  # South Pole receives random points

    ### 3.STEP
        # Simulation of temperature gain/loss
    if (iteration % freq_gain_loss == 0) :
        temp_gain_eq = 8
        temp_loss_pol = 4
        if iteration >= timestep_globalwarming:
            temp_loss_pol = 3
        temperature_grid[1, :] += temp_gain_eq  # Add 4 temperature points at the equator
        temperature_grid[[0, 2], :] -= temp_loss_pol  # Subtract 2 temperature points at the poles

    # track mean temperature
    mean_temp[iteration] = np.mean(temperature_grid)
    # track temp grid
    temp_grid_array[iteration, :, :] = temperature_grid

    #Display current temperature after every 5th iteration
    if iteration % freq_plot == 0:
        plt.figure()
        plt.imshow(temperature_grid, cmap='coolwarm', interpolation='nearest',
                    vmin = -20, vmax = 70)
        plt.colorbar(label='Temperature')
        plt.title("Temperature Grid after iteration:"+str(iteration))
        plt.yticks([2, 1, 0], ['South Hemisphere', 'Tropics', 'North Hemisphere'])


    print("Temperature Grid after iteration:" + str(iteration))
    print(temperature_grid)

print("Final Temperature Grid After Simulation:")
print(temperature_grid)
plt.show()

# plot mean temperature curve
plt.figure()
plt.plot(mean_temp)
plt.ylim(0,20)
plt.title('Global mean temperature')

# Plot time series for all positions in subplots
fig, axs = plt.subplots(grid_size, grid_size, figsize=(12, 12))
fig.suptitle('Temperature Time Series for All Positions', fontsize=16)
for i in range(grid_size):
    for j in range(grid_size):
        axs[i, j].plot(temp_grid_array[:, i, j], label=f'Position ({i}, {j})')
        axs[i, j].set_ylim(-20, 70)
        axs[i, j].set_xlabel('Iteration')
        axs[i, j].set_ylabel('Temperature')
        if i == 0:
          axs[i, j].set_title(f'Position ({i}, {j}) - NH')
        if i == 1:
          axs[i, j].set_title(f'Position ({i}, {j}) - EQ')
        if i == 2:
          axs[i, j].set_title(f'Position ({i}, {j}) - SH')
plt.tight_layout()
plt.show()



